// Regenerate only the fictional public catalogue; no browser data is imported.
// Run with `node supabase/generate-seed.mjs` from the repository root.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';

const root = path.resolve(import.meta.dirname, '..');
const modules = new Map();

function loadSource(relativePath) {
  const filename = path.resolve(root, relativePath);
  if (modules.has(filename)) return modules.get(filename).exports;
  const module = { exports: {} };
  modules.set(filename, module);
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;
  const requireSource = (specifier) => {
    if (!specifier.startsWith('./'))
      throw new Error(`Unexpected seed import: ${specifier}`);
    return loadSource(
      path.relative(
        root,
        path.resolve(path.dirname(filename), `${specifier}.ts`),
      ),
    );
  };
  vm.runInNewContext(
    compiled,
    { exports: module.exports, module, require: requireSource },
    { filename },
  );
  return module.exports;
}

const { listings } = loadSource('src/data.ts');
const { getListingCoordinates } = loadSource('src/geography.ts');
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const sql = [
  '-- Generated by supabase/generate-seed.mjs from the fictional public demo catalogue.',
  '-- All businesses, providers, reviews, and prices are examples. No customer data.',
  '-- Optional: apply after the marketplace migration to populate a demo project.',
  'begin;',
];

for (const listing of listings) {
  const { services, ...data } = listing;
  data.coordinates = getListingCoordinates(listing);
  sql.push(
    `insert into public.listings(id, owner_id, is_demo, data) values (${quote(listing.id)}, null, true, ${quote(JSON.stringify(data))}::jsonb) on conflict (id) do nothing;`,
  );
  for (const service of services) {
    sql.push(
      `insert into public.services(id, listing_id, name, description, duration, price) values (${quote(service.id)}, ${quote(listing.id)}, ${quote(service.name)}, ${quote(service.description)}, ${service.duration}, ${service.price}) on conflict (id) do nothing;`,
    );
  }
}
sql.push('commit;', '');
fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql.join('\n'));
console.log(
  `Wrote ${listings.length} fictional listings to supabase/seed.sql.`,
);
